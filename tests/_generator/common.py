def tags_short_str(rec):
    return "; ".join("%s — %s" % (t, rec["tags_short"][t]) for t in rec["tags"])


def ctx_doc(records, order, stand_note):
    rows = ["| server-name | conn-ip | conn-user | tags | short-desc | tags-short-desc |", "|---|---|---|---|---|---|"]
    for n in order:
        r = records[n]
        rows.append("| %s | %s | evalbot | %s | %s | %s |" % (r["name"], r["ip"], ", ".join(r["tags"]), r["short"], tags_short_str(r)))
    return stand_note + "\n\n" + "\n".join(rows)


